// Builds src/content/words-a2.ts from the CEFR-J Vocabulary Profile 1.5 CSV.
// Source: https://github.com/openlanguageprofiles/olp-en-cefrj (Tono Laboratory, TUFS)
// Usage: node scripts/build-wordlist.mjs path/to/cefrj-vocabulary-profile-1.5.csv
import { readFileSync, writeFileSync } from 'node:fs';

const KEEP_POS = new Set(['noun', 'verb', 'adjective', 'adverb']);

function parseCsvLine(line) {
  const out = [];
  let cur = '';
  let quoted = false;
  for (const ch of line) {
    if (ch === '"') quoted = !quoted;
    else if (ch === ',' && !quoted) { out.push(cur); cur = ''; }
    else cur += ch;
  }
  out.push(cur);
  return out;
}

const [, , csvPath] = process.argv;
const lines = readFileSync(csvPath, 'utf8').split(/\r?\n/).slice(1).filter(Boolean);
const seen = new Set();
const words = [];
for (const line of lines) {
  const [headword, pos, level, ...topicCols] = parseCsvLine(line);
  if (level !== 'A2' || !KEEP_POS.has(pos)) continue;
  const word = headword.split('/')[0].trim();
  const key = `${word}|${pos}`;
  if (!word || seen.has(key)) continue;
  seen.add(key);
  const topics = [...new Set(topicCols.flatMap((c) => c.split(',')).map((t) => t.trim()).filter(Boolean))];
  words.push(topics.length ? { word, pos, topics } : { word, pos });
}
writeFileSync('src/content/words-a2.ts', `// Generated by scripts/build-wordlist.mjs — do not edit by hand.\n// CEFR-J Wordlist Version 1.5, compiled by Yukio Tono, Tokyo University of Foreign Studies.\nexport type WordEntry = { word: string; pos: string; topics?: string[] };\nexport const A2_WORDS: WordEntry[] = ${JSON.stringify(words)};\n`);
console.log(`wrote ${words.length} words`);
